#!/usr/bin/env bash
# Vendors a pinned mermaid build into Vendor/mermaid (shipped in the app's Resources/Vendor).
#
#   scripts/vendor-mermaid.sh 12.3.0     (or: make vendor-mermaid MERMAID_VERSION=12.3.0)
#
# Installs mermaid@VERSION from the npm registry into a temporary folder (npm checks each
# tarball against the registry's integrity hash; install scripts never run), then copies
# dist/mermaid.min.js and mermaid's MIT license, writes NOTICES (the license text of every
# package mermaid depends on at run time, copied from its published tarball: mermaid.min.js
# bundles them), and records the version, the tarball's integrity, the file's SHA-256, and the
# packages in MANIFEST. A package without a license file fails the script, so a new release
# gets a human look. Needs Node.js and npm (vendoring only; the app never runs them).
set -euo pipefail

VERSION="${1:-}"
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "usage: $0 VERSION (e.g. 12.3.0)" >&2
  exit 64
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR_DIR="$ROOT/Vendor/mermaid"
REGISTRY="https://registry.npmjs.org/"

WORK="$(mktemp -d)"
trap 'command rm -rf "$WORK"' EXIT

mkdir -p "$WORK/install"
printf '{ "name": "peep-vendor-mermaid", "private": true }\n' >"$WORK/install/package.json"
(
  cd "$WORK/install"
  npm install --registry="$REGISTRY" --ignore-scripts --omit=dev --no-audit --no-fund --no-save \
    --no-package-lock "mermaid@$VERSION" >/dev/null
)

MODULES="$WORK/install/node_modules"
SOURCE="$MODULES/mermaid/dist/mermaid.min.js"
installed="$(node -p 'require(process.argv[1]).version' "$MODULES/mermaid/package.json")"
if [[ "$installed" != "$VERSION" ]]; then
  echo "error: npm installed mermaid $installed, not $VERSION" >&2
  exit 1
fi
integrity="$(npm view --registry="$REGISTRY" "mermaid@$VERSION" dist.integrity)"
sum="$(shasum -a 256 "$SOURCE" | cut -d' ' -f1)"

# Every installed package but mermaid and type-only `@types/*` packages, by name and version,
# with its license text. Writes NOTICES and the package list for MANIFEST.
node - "$MODULES" "$WORK/NOTICES" "$WORK/packages" "$VERSION" <<'NODE'
const fs = require("fs");
const path = require("path");
const [modules, noticesPath, packagesPath, version] = process.argv.slice(2);

function packageFolders(folder) {
  const found = [];
  if (!fs.existsSync(folder)) return found;
  for (const entry of fs.readdirSync(folder)) {
    if (entry.startsWith(".")) continue;
    const full = path.join(folder, entry);
    if (entry.startsWith("@")) {
      for (const scoped of fs.readdirSync(full)) found.push(path.join(full, scoped));
    } else {
      found.push(full);
    }
  }
  return found.flatMap((folder) => [folder, ...packageFolders(path.join(folder, "node_modules"))]);
}

const packages = new Map();
for (const folder of packageFolders(modules)) {
  const manifest = JSON.parse(fs.readFileSync(path.join(folder, "package.json"), "utf8"));
  if (manifest.name === "mermaid" || manifest.name.startsWith("@types/")) continue;
  const key = `${manifest.name}@${manifest.version}`;
  if (packages.has(key)) continue;
  const files = fs.readdirSync(folder).filter((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name)).sort();
  if (files.length === 0) {
    console.error(`error: ${key} has no license file`);
    process.exit(1);
  }
  const text = files
    .map((name) => fs.readFileSync(path.join(folder, name), "utf8").replace(/\r\n?/g, "\n").trim())
    .join("\n\n");
  const license = typeof manifest.license === "string" ? manifest.license : "see below";
  packages.set(key, { name: manifest.name, version: manifest.version, license, text });
}

const sorted = [...packages.values()].sort((a, b) =>
  a.name === b.name ? a.version.localeCompare(b.version, "en", { numeric: true }) : a.name.localeCompare(b.name));
const notices = [
  `Third-party notices for mermaid ${version} (Vendor/mermaid/mermaid.min.js bundles these packages).`,
  "Generated by scripts/vendor-mermaid.sh from each package's npm tarball. Do not edit.",
  ...sorted.map((p) => `--------\n${p.name} ${p.version} (${p.license})\n\n${p.text}`),
].join("\n\n") + "\n";
fs.writeFileSync(noticesPath, notices);
fs.writeFileSync(packagesPath, sorted.map((p) => `package ${p.name} ${p.version} ${p.license}`).join("\n") + "\n");
NODE

{
  echo "# mermaid vendored by scripts/vendor-mermaid.sh. Do not edit."
  echo "version $VERSION"
  echo "license MIT (https://github.com/mermaid-js/mermaid/blob/mermaid@$VERSION/LICENSE)"
  echo "integrity $integrity (${REGISTRY}mermaid/-/mermaid-$VERSION.tgz)"
  echo "# sha256 file"
  echo "$sum mermaid.min.js (package/dist/mermaid.min.js)"
  echo "# packages bundled in mermaid.min.js (npm's resolution at vendoring time; licenses in NOTICES)"
  cat "$WORK/packages"
} >"$WORK/MANIFEST"

mkdir -p "$VENDOR_DIR"
command cp -f "$SOURCE" "$VENDOR_DIR/mermaid.min.js"
command cp -f "$MODULES/mermaid/LICENSE" "$VENDOR_DIR/LICENSE"
command cp -f "$WORK/NOTICES" "$VENDOR_DIR/NOTICES"
command cp -f "$WORK/MANIFEST" "$VENDOR_DIR/MANIFEST"
echo "Vendored mermaid $VERSION:"
sed -n '1,6p' "$VENDOR_DIR/MANIFEST"
